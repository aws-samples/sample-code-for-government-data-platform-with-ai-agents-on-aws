CREATE MATERIALIZED VIEW rs_fact_school_performance AS
SELECT
    geography_code::VARCHAR(20),
    la_name::VARCHAR(200),
    calendar_year::INT,
    time_period::VARCHAR(20),
    time_identifier::VARCHAR(50),
    version::VARCHAR(20),
    breakdown_topic::VARCHAR(100),
    gender::VARCHAR(20),
    ethnicity::VARCHAR(100),
    ethnicity_minor::VARCHAR(100),
    disadvantage::VARCHAR(50),
    fsm::VARCHAR(50),
    sen::VARCHAR(50),
    sen_status::VARCHAR(50),
    sen_primary_need::VARCHAR(100),
    first_language::VARCHAR(100),
    prior_attainment::VARCHAR(50),
    ks2_scaled_score_group::VARCHAR(50),
    mobility::VARCHAR(50),
    young_carer::VARCHAR(50),
    school_admission_type::VARCHAR(100),
    school_religious_character::VARCHAR(100),
    TRY_CAST(t_cohort AS FLOAT) AS t_cohort,
    TRY_CAST(avg_att8 AS FLOAT) AS avg_att8,
    TRY_CAST(pt_l2basics_94 AS FLOAT) AS pt_l2basics_94,
    TRY_CAST(pt_l2basics_95 AS FLOAT) AS pt_l2basics_95
FROM gold.fact_school_performance;
